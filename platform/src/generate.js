// Builds the pm2 ecosystem file and the nginx config from the schools table.
// Every value written here is either from validated config or validated at school creation (code, subdomain, port).
const fs = require('fs');
const path = require('path');
const { cfg } = require('./config');
const { db } = require('./db');

const CODE_RE = /^[a-z][a-z0-9]{1,19}$/;
const SUB_RE = /^[a-z0-9](?:[a-z0-9-]{0,30}[a-z0-9])?$/;
const RESERVED = new Set(['www', 'api', 'console', 'admin', 'mail', 'ftp', 'platform', 'static', 'cdn', 'app']);

const liveSchools = () => db.prepare("SELECT * FROM schools WHERE status != 'archived' ORDER BY id").all();

const schoolDir = (code) => path.join(cfg.schoolsDir, code);
const envPath = (code) => path.join(schoolDir(code), 'backend.env');

function parseEnv(file) {
  const out = {};
  if (!fs.existsSync(file)) return out;
  for (const line of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
    const m = /^([A-Z][A-Z0-9_]*)=(.*)$/.exec(line.trim());
    if (m) out[m[1]] = m[2];
  }
  return out;
}

function assertSafe(s) {
  if (!CODE_RE.test(s.code) || !SUB_RE.test(s.subdomain) || !Number.isInteger(s.port)) {
    throw new Error(`School #${s.id} has an invalid code, subdomain or port; fix it before generating config`);
  }
}

function ecosystem({ mask = false } = {}) {
  const apps = [{
    name: 'erp-frontend', cwd: cfg.frontendDir, script: 'npm', args: 'start',
    env: { NODE_ENV: 'production', PORT: String(cfg.frontendPort) }, max_memory_restart: '600M',
  }];
  for (const s of liveSchools()) {
    assertSafe(s);
    const env = parseEnv(envPath(s.code));
    if (mask) for (const k of ['JWT_SECRET', 'LICENSE_KEY']) if (env[k]) env[k] = '••••••';
    apps.push({ name: `erp-school-${s.code}`, cwd: cfg.backendDir, script: 'src/server.js', env, max_memory_restart: '300M', time: true });
  }
  return `// Generated by the School ERP platform console. Do not edit by hand; use the console's System page.\n`
    + `module.exports = ${JSON.stringify({ apps }, null, 2)};\n`;
}

const proxy = (port) => [
  `    proxy_pass http://127.0.0.1:${port};`,
  '    proxy_http_version 1.1;',
  '    proxy_set_header Host $host;',
  '    proxy_set_header X-Real-IP $remote_addr;',
  '    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;',
  '    proxy_set_header X-Forwarded-Proto $scheme;',
  '    proxy_set_header Upgrade $http_upgrade;',
  '    proxy_set_header Connection "upgrade";',
  '    proxy_read_timeout 120s;',
].join('\n');

function appLocations(apiPort) {
  return [
    '  client_max_body_size 25m;',
    `  location /api/ {\n${proxy(apiPort)}\n  }`,
    `  location /iclock/ {\n${proxy(apiPort)}\n  }`,
    `  location / {\n${proxy(cfg.frontendPort)}\n  }`,
  ].join('\n');
}

function serverBlocks(host, port, isConsole = false) {
  const inner = isConsole ? `  client_max_body_size 5m;\n  location / {\n${proxy(port)}\n  }` : appLocations(port);
  if (cfg.sslMode === 'none') {
    return `server {\n  listen 80;\n  listen [::]:80;\n  server_name ${host};\n${inner}\n}\n`;
  }
  // Most eSSL ADMS firmware can't do HTTPS, so /iclock stays reachable over plain HTTP.
  const http = [
    'server {', '  listen 80;', '  listen [::]:80;', `  server_name ${host};`,
    '  location /.well-known/acme-challenge/ { root /var/www/certbot; }',
    isConsole ? '' : `  location /iclock/ {\n${proxy(port)}\n  }`,
    '  location / { return 301 https://$host$request_uri; }', '}',
  ].filter(Boolean).join('\n');
  const https = [
    'server {', '  listen 443 ssl;', '  listen [::]:443 ssl;', '  http2 on;', `  server_name ${host};`,
    `  ssl_certificate /etc/letsencrypt/live/${cfg.certName}/fullchain.pem;`,
    `  ssl_certificate_key /etc/letsencrypt/live/${cfg.certName}/privkey.pem;`,
    '  add_header Strict-Transport-Security "max-age=31536000" always;',
    inner, '}',
  ].join('\n');
  return `${http}\n${https}\n`;
}

function nginx() {
  const parts = [`# Generated by the School ERP platform console (${new Date().toISOString()}). Do not edit by hand.\n`];
  parts.push(`# Owner console\n${serverBlocks(cfg.consoleHost, cfg.port, true)}`);
  for (const s of liveSchools()) {
    assertSafe(s);
    parts.push(`# ${s.code}: ${String(s.name).replace(/[\r\n#]/g, ' ')}\n${serverBlocks(`${s.subdomain}.${cfg.baseDomain}`, s.port)}`);
  }
  return parts.join('\n');
}

function writeAll() {
  fs.mkdirSync(path.dirname(cfg.ecosystemPath), { recursive: true });
  fs.mkdirSync(path.dirname(cfg.nginxConfPath), { recursive: true });
  // The ecosystem file contains every school's secrets.
  fs.writeFileSync(cfg.ecosystemPath, ecosystem(), { mode: 0o600 });
  fs.writeFileSync(cfg.nginxConfPath, nginx(), { mode: 0o644 });
  return { ecosystem: cfg.ecosystemPath, nginx: cfg.nginxConfPath };
}

module.exports = { ecosystem, nginx, writeAll, parseEnv, envPath, schoolDir, CODE_RE, SUB_RE, RESERVED };
