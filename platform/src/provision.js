// Creating, updating and archiving schools.
const fs = require('fs');
const net = require('net');
const path = require('path');
const crypto = require('crypto');
const { execFile } = require('child_process');
const { cfg } = require('./config');
const { db, log } = require('./db');
const { newKey, sha256, localToday, PUBLIC_KEY_PATH } = require('./licence');
const { writeAll, envPath, schoolDir, CODE_RE, SUB_RE, RESERVED } = require('./generate');

const httpError = (status, message) => Object.assign(new Error(message), { status });
const isDate = (v) => typeof v === 'string' && /^\d{4}-\d{2}-\d{2}$/.test(v) && !Number.isNaN(Date.parse(v));
const addMonths = (date, months) => {
  const d = new Date(`${date}T12:00:00`);
  d.setMonth(d.getMonth() + months);
  const p = (n) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}`;
};
const addDays = (date, days) => {
  const d = new Date(`${date}T12:00:00`);
  d.setDate(d.getDate() + days);
  const p = (n) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}`;
};
const tempPassword = () => crypto.randomBytes(9).toString('base64').replace(/[^a-zA-Z0-9]/g, '').slice(0, 10).padEnd(10, '7');

function portFree(port) {
  return new Promise((resolve) => {
    const srv = net.createServer().once('error', () => resolve(false)).once('listening', () => srv.close(() => resolve(true)));
    srv.listen(port, '127.0.0.1');
  });
}

async function allocatePort() {
  const used = new Set(db.prepare('SELECT port FROM schools').all().map(r => r.port));
  for (let p = cfg.portRangeStart; p < cfg.portRangeStart + 2000; p++) {
    if (used.has(p) || p === cfg.port || p === cfg.frontendPort) continue;
    if (await portFree(p)) return p;
  }
  throw httpError(500, 'No free port left in the configured range');
}

function validateDetails(b, { creating }) {
  const out = {};
  if (creating || 'name' in b) {
    out.name = String(b.name || '').trim();
    if (out.name.length < 3 || out.name.length > 120) throw httpError(400, 'School name must be 3–120 characters');
  }
  for (const f of ['contact_name', 'contact_phone', 'contact_email', 'notes']) if (f in b) out[f] = String(b[f] || '').trim().slice(0, 500) || null;
  if (out.contact_email && !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(out.contact_email)) throw httpError(400, 'Contact email is not valid');
  if (out.contact_phone && !/^\+?[\d\s-]{7,15}$/.test(out.contact_phone)) throw httpError(400, 'Contact phone is not valid');
  if ('max_students' in b) {
    if (b.max_students === '' || b.max_students == null) out.max_students = null;
    else {
      const n = Number(b.max_students);
      if (!Number.isInteger(n) || n < 1) throw httpError(400, 'Student limit must be a whole number, or blank to use the plan limit');
      out.max_students = n;
    }
  }
  if (creating || 'plan_id' in b) {
    const plan = db.prepare('SELECT id FROM plans WHERE id = ? AND active = 1').get(Number(b.plan_id));
    if (!plan) throw httpError(400, 'Choose a valid plan');
    out.plan_id = plan.id;
  }
  if ('expires_on' in b && b.expires_on) {
    if (!isDate(b.expires_on)) throw httpError(400, 'Expiry must be a date (YYYY-MM-DD)');
    out.expires_on = b.expires_on;
  }
  return out;
}

function writeSchoolEnv(school, jwtSecret) {
  const dir = schoolDir(school.code);
  const scheme = cfg.sslMode === 'none' ? 'http' : 'https';
  const env = {
    NODE_ENV: 'production',
    PORT: String(school.port),
    JWT_SECRET: jwtSecret,
    JWT_EXPIRES_IN: '1d',
    CORS_ORIGIN: `${scheme}://${school.subdomain}.${cfg.baseDomain}`,
    TZ: 'Asia/Kolkata',
    DB_PATH: path.join(dir, 'data', 'school.sqlite'),
    UPLOAD_DIR: path.join(dir, 'uploads'),
    BACKUP_DIR: path.join(dir, 'backups'),
    LICENSE_SERVER_URL: cfg.publicUrl,
    LICENSE_KEY: school.licence_key,
    LICENSE_PUBLIC_KEY_FILE: PUBLIC_KEY_PATH,
    LICENSE_CACHE_FILE: path.join(dir, 'data', 'licence-cache.json'),
  };
  const text = `# Backend settings for ${school.code}. Generated by the platform console; add SMS/SMTP settings below.\n`
    + Object.entries(env).map(([k, v]) => `${k}=${v}`).join('\n') + '\n';
  fs.writeFileSync(envPath(school.code), text, { mode: 0o600 });
  return env;
}

function initDatabase(env, schoolName) {
  const password = tempPassword();
  return new Promise((resolve, reject) => {
    execFile(cfg.nodeBin, [path.join(__dirname, 'init-school.js')], {
      cwd: cfg.backendDir,
      timeout: 120000,
      env: {
        PATH: process.env.PATH, HOME: process.env.HOME, ...env,
        BACKEND_DIR: cfg.backendDir, INIT_SCHOOL_NAME: schoolName, INIT_ADMIN_USERNAME: 'admin', INIT_ADMIN_PASSWORD: password,
      },
    }, (err, stdout, stderr) => {
      if (err) return reject(httpError(500, `Could not create the school database: ${(stderr || err.message).trim().slice(0, 300)}`));
      resolve({ username: 'admin', password });
    });
  });
}

async function createSchool(body, ownerId) {
  const code = String(body.code || '').trim().toLowerCase();
  const subdomain = String(body.subdomain || code).trim().toLowerCase();
  if (!CODE_RE.test(code)) throw httpError(400, 'Code: 2–20 lowercase letters/digits, starting with a letter (e.g. dps2)');
  if (!SUB_RE.test(subdomain) || RESERVED.has(subdomain)) throw httpError(400, 'Subdomain: lowercase letters, digits and dashes (not www, api, console …)');
  if (db.prepare('SELECT 1 FROM schools WHERE code = ? OR subdomain = ?').get(code, subdomain)) throw httpError(409, 'That code or subdomain is already used');
  const d = validateDetails(body, { creating: true });
  const starts = isDate(body.starts_on) ? body.starts_on : localToday();
  const trialDays = Number(body.trial_days ?? 30);
  if (!Number.isInteger(trialDays) || trialDays < 0 || trialDays > 365) throw httpError(400, 'Trial days must be 0–365');
  const expires = d.expires_on || addDays(starts, trialDays);
  const status = body.status === 'active' ? 'active' : 'trial';

  const dir = schoolDir(code);
  if (fs.existsSync(dir)) throw httpError(409, `Folder ${dir} already exists; archive or remove it first`);
  const port = await allocatePort();
  const key = newKey();
  for (const sub of ['data', 'uploads', 'backups']) fs.mkdirSync(path.join(dir, sub), { recursive: true, mode: 0o750 });

  const info = db.prepare(`
    INSERT INTO schools (code, name, subdomain, plan_id, status, starts_on, expires_on, max_students, port, licence_key, licence_key_hash,
      contact_name, contact_phone, contact_email, notes)
    VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`).run(
    code, d.name, subdomain, d.plan_id, status, starts, expires, d.max_students ?? null, port, key, sha256(key),
    d.contact_name ?? null, d.contact_phone ?? null, d.contact_email ?? null, d.notes ?? null);
  const school = db.prepare('SELECT * FROM schools WHERE id = ?').get(info.lastInsertRowid);
  try {
    const env = writeSchoolEnv(school, crypto.randomBytes(32).toString('hex'));
    const admin = await initDatabase(env, school.name);
    const files = writeAll();
    log('school.create', { schoolId: school.id, ownerId, detail: `${code} on port ${port}` });
    return { school: publicSchool(school), admin, files, url: `${cfg.sslMode === 'none' ? 'http' : 'https'}://${subdomain}.${cfg.baseDomain}` };
  } catch (e) {
    // Leave nothing half-made behind.
    db.prepare('DELETE FROM schools WHERE id = ?').run(school.id);
    fs.rmSync(dir, { recursive: true, force: true });
    throw e;
  }
}

function updateSchool(id, body, ownerId) {
  const s = getSchool(id);
  const d = validateDetails(body, { creating: false });
  const sets = Object.keys(d);
  if (!sets.length) throw httpError(400, 'Nothing to change');
  db.prepare(`UPDATE schools SET ${sets.map(k => `${k} = ?`).join(', ')} WHERE id = ?`).run(...sets.map(k => d[k]), s.id);
  if (d.name) {
    // Keep the generated nginx comment in sync; the school's own settings name is managed inside the ERP.
    writeAll();
  }
  log('school.update', { schoolId: s.id, ownerId, detail: sets.join(', ') });
  return publicSchool(getSchool(s.id));
}

function setStatus(id, status, ownerId) {
  const s = getSchool(id);
  if (!['active', 'suspended', 'trial'].includes(status)) throw httpError(400, 'Invalid status');
  db.prepare('UPDATE schools SET status = ? WHERE id = ?').run(status, s.id);
  log(`school.${status === 'suspended' ? 'suspend' : 'resume'}`, { schoolId: s.id, ownerId });
  return publicSchool(getSchool(s.id));
}

function renew(id, body, ownerId) {
  const s = getSchool(id);
  const months = Number(body.months);
  if (!Number.isInteger(months) || months < 1 || months > 60) throw httpError(400, 'Months must be 1–60');
  const amount = Number(body.amount || 0);
  if (!(amount >= 0)) throw httpError(400, 'Amount must be 0 or more');
  const paidOn = isDate(body.paid_on) ? body.paid_on : localToday();
  // Renewing early extends from the current expiry; renewing late starts from today.
  const from = s.expires_on > localToday() ? s.expires_on : localToday();
  const newExpiry = addMonths(from, months);
  db.transaction(() => {
    db.prepare(`INSERT INTO renewals (school_id, paid_on, amount, months, old_expires_on, new_expires_on, mode, reference, note, owner_id)
      VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`).run(s.id, paidOn, amount, months, s.expires_on, newExpiry,
      String(body.mode || '').slice(0, 40) || null, String(body.reference || '').slice(0, 80) || null, String(body.note || '').slice(0, 300) || null, ownerId);
    db.prepare("UPDATE schools SET expires_on = ?, status = CASE WHEN status IN ('trial','expired') THEN 'active' ELSE status END WHERE id = ?").run(newExpiry, s.id);
  })();
  log('school.renew', { schoolId: s.id, ownerId, detail: `${months} months to ${newExpiry}, ₹${amount}` });
  return publicSchool(getSchool(s.id));
}

function archive(id, confirmCode, ownerId) {
  const s = getSchool(id);
  if (confirmCode !== s.code) throw httpError(400, `Type the school code (${s.code}) to confirm`);
  const dir = schoolDir(s.code);
  const stamp = new Date().toISOString().replace(/[-:]/g, '').replace(/\..*/, '').replace('T', '-');
  const dest = path.join(cfg.schoolsDir, '_archive', `${s.code}-${stamp}`);
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  if (fs.existsSync(dir)) fs.renameSync(dir, dest);
  db.prepare("UPDATE schools SET status = 'archived', archived_at = CURRENT_TIMESTAMP, archive_path = ?, subdomain = subdomain || '-archived-' || id, code = code || '-archived-' || id WHERE id = ?")
    .run(dest, s.id);
  writeAll();
  log('school.archive', { schoolId: s.id, ownerId, detail: dest });
  return { archived: true, archive_path: dest, code: s.code };
}

function getSchool(id) {
  const s = db.prepare('SELECT * FROM schools WHERE id = ?').get(Number(id));
  if (!s) throw httpError(404, 'School not found');
  return s;
}

function publicSchool(s) {
  const { licence_key, licence_key_hash, ...rest } = s;
  return rest;
}

module.exports = { createSchool, updateSchool, setStatus, renew, archive, getSchool, publicSchool, addMonths, httpError, isDate };
